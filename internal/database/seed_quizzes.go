// SeedQuizzes seeds all 5 quizzes, 25 questions, and 100 options
func SeedQuizzes(db *gorm.DB) {
	bundles := getSeedQuizBundles()
	for _, b := range bundles {
		var existing models.Quiz
		if err := db.Where("id = ?", b.Quiz.ID).First(&existing).Error; err != nil {
			db.Create(&b.Quiz)
		} else {
			existing.Title = b.Quiz.Title
			existing.DurationMins = b.Quiz.DurationMins
			existing.TotalQuestions = b.Quiz.TotalQuestions
			existing.PassingScore = b.Quiz.PassingScore
			db.Save(&existing)
		}

		for _, q := range b.Questions {
			var existingQ models.QuizQuestion
			if err := db.Where("id = ?", q.ID).First(&existingQ).Error; err != nil {
				db.Create(&q)
			} else {
				existingQ.QuestionText = q.QuestionText
				existingQ.Explanation = q.Explanation
				existingQ.OrderNum = q.OrderNum
				existingQ.CorrectOption = q.CorrectOption
				db.Save(&existingQ)
			}
		}

		for _, opt := range b.Options {
			var existingOpt models.QuizOption
			if err := db.Where("id = ?", opt.ID).First(&existingOpt).Error; err != nil {
				db.Create(&opt)
			} else {
				existingOpt.Text = opt.Text
				existingOpt.Index = opt.Index
				db.Save(&existingOpt)
			}
		}
	}
	log.Printf("✅ Verified / Seeded %d quizzes with full questions and options!", len(bundles))
}
